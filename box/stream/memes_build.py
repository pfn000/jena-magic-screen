#!/usr/bin/env python3
"""Build api/_lib/memes-data.js (what Jena's brain path reads, bundled with the site) from public/memes.json and
public/sounds/index.json.  Run from the repo root before a site push:  python3 box/stream/memes_build.py [repo_dir]
Only entries in "memes" go to her brain; "trending" candidates (from the weekly refresh) wait for review.
Kid-safe: entries marked kid_safe false are skipped and crude words in the text are masked."""
import json, os, re, sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.getcwd()
CRUDE = re.compile(r"\b(shit|fuck\w*|bitch\w*|ass|dick|nuts|sex\w*|horny)\b", re.I)

def mask(t):
    return CRUDE.sub(lambda m: m.group(0)[0] + "*" * (len(m.group(0)) - 1), re.sub(r"\s+", " ", str(t or "")).strip())

def short(t, n=220):
    t = mask(t)
    return t if len(t) <= n else t[:n].rsplit(" ", 1)[0] + "\u2026"

def keys(m):
    if m.get("keys"): return m["keys"]
    t = re.sub(r"'s\b", "", m["name"].lower())
    return [w for w in re.sub(r"[^a-z0-9 ]+", " ", t).split() if len(w) > 2]

def build(root=ROOT):
    memes = json.load(open(os.path.join(root, "public/memes.json")))
    sounds = json.load(open(os.path.join(root, "public/sounds/index.json")))
    ids = {s["id"] for s in sounds["sounds"]}
    out = {"memes": [], "sounds": []}
    for m in memes["memes"]:
        if m.get("kid_safe") is False: continue
        out["memes"].append({"n": m["name"], "k": keys(m), "m": short(m.get("meaning")), "u": mask(m.get("how_used")),
                             "s": m.get("sound") if m.get("sound") in ids else None, "y": m.get("year") or m.get("era")})
    for s in sounds["sounds"]:
        if s.get("kid_safe") is False or s.get("hidden") or s.get("scream"): continue   # retention clips are the stream page's, not her brain's
        out["sounds"].append({"id": s["id"], "t": s.get("tags", []), "w": s.get("when", "")})
    js = ("// GENERATED by box/stream/memes_build.py from public/memes.json + public/sounds/index.json. Do not edit by hand.\n"
          "export default " + json.dumps(out, ensure_ascii=True, separators=(",", ":")) + ";\n")
    open(os.path.join(root, "api/_lib/memes-data.js"), "w").write(js)
    return len(out["memes"]), len(out["sounds"])

if __name__ == "__main__":
    print("memes-data.js: %d memes, %d sounds" % build())
